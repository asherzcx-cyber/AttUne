-- Run in a Snowflake worksheet. This stores de-identified analytics exports,
-- not raw passwords, API keys, or camera frames.
CREATE DATABASE IF NOT EXISTS ATTUNE_ANALYTICS;
CREATE SCHEMA IF NOT EXISTS ATTUNE_ANALYTICS.PUBLIC;

CREATE TABLE IF NOT EXISTS ATTUNE_ANALYTICS.PUBLIC.SESSION_SUMMARIES (
  SESSION_ID VARCHAR,
  USER_PSEUDONYM VARCHAR,
  EXERCISE VARCHAR,
  STARTED_AT TIMESTAMP_TZ,
  AVERAGE_FOCUS NUMBER(5,2),
  SAMPLE_COUNT NUMBER,
  SOURCE VARCHAR,
  EXPORTED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

-- This view is a demo-ready analytics surface for weekly change trends.
CREATE OR REPLACE VIEW ATTUNE_ANALYTICS.PUBLIC.WEEKLY_FOCUS_TREND AS
SELECT DATE_TRUNC('WEEK', STARTED_AT) AS WEEK,
       COUNT(*) AS SESSIONS,
       AVG(AVERAGE_FOCUS) AS AVERAGE_FOCUS
FROM ATTUNE_ANALYTICS.PUBLIC.SESSION_SUMMARIES
GROUP BY 1
ORDER BY 1 DESC;
